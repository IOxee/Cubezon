/** Spanish name of a material; unknown ids are shown humanized ("zombie_head" -> "Zombie head"). */
export function itemName(material: string): string {
  const known = itemNames[material];
  if (known) return known;

  for (const [color, names] of Object.entries(colorNames)) {
    if (!material.startsWith(color + "_")) continue;
    const variant = colored[material.slice(color.length + 1)];
    if (variant) return `${variant.name} ${names[variant.gender]}`;
  }

  const text = material.replace(/_/g, " ");
  return text.charAt(0).toUpperCase() + text.slice(1);
}
